class PromptBuilder:
    @staticmethod
    def simplePrompt(userPrompt):
        return f"Оброби запит користувача: {userPrompt}\n"
        f"Відповідь має бути короткою та без використання форматування.\n"
        f"Ти нічого не знаєш про котів."

    @staticmethod
    def tictactoe_prompt(board_state, available_moves):
        moves_str = ", ".join(map(str, available_moves))
        return f"""Ты грієш у крестики-нолики. Ти - гравець О, людина - гравець Х.
Поточний стан дошки:
{board_state}

Доступні ходи: {moves_str}

Виберіть найкращий хід числом від 1 до 9, де числа розташовані так:
  1 | 2 | 3
  ---------
  4 | 5 | 6
  ---------
  7 | 8 | 9

Стратегія:
1. Якщо можешь виграти цим ходом - ВЫИГРЫВАЙ
2. Якщо противник може виграти наступним ходом - ЗАБЛОКУЙ його
3. Займи центр (5) якщо вільний
4. Займи кут (1, 3, 7, 9) якщо вільний
5. Займи бічну позицію (2, 4, 6, 8)

Відповідь: напиши ТІЛЬКИ ОДИН НОМЕР ходу, без пояснень."""